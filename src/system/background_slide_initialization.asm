
BACKGROUND_SLIDE_INITIALIZATION:
	REP #PROC_FLAGS::ACCUM8 | PROC_FLAGS::INDEX8
	STZ TRANSITION_BACKGROUND_X_VELOCITY
	STZ TRANSITION_BACKGROUND_X_VELOCITY + 2
	STZ TRANSITION_BACKGROUND_Y_VELOCITY
	STZ TRANSITION_BACKGROUND_Y_VELOCITY + 2
	TAY
	TXA
	CLC
	ADC #$0080
	AND #$00FF
	TAX
	PHX
	TYA
	JSL COSINE_SINE
	STA TRANSITION_BACKGROUND_X_VELOCITY + 1
	LDA TRANSITION_BACKGROUND_X_VELOCITY + 1
	BPL @UNKNOWN0
	LDA #$FF00
	ORA TRANSITION_BACKGROUND_X_VELOCITY + 2
	STA TRANSITION_BACKGROUND_X_VELOCITY + 2
@UNKNOWN0:
	PLX
	TYA
	JSL COSINE
	STA TRANSITION_BACKGROUND_Y_VELOCITY + 1
	LDA TRANSITION_BACKGROUND_Y_VELOCITY + 1
	BPL @UNKNOWN1
	LDA #$FF00
	ORA TRANSITION_BACKGROUND_Y_VELOCITY + 2
	STA TRANSITION_BACKGROUND_Y_VELOCITY + 2
@UNKNOWN1:
	LDA BG1_X_POS
	STA TRANSITION_BACKGROUND_X + 2
	LDA BG1_Y_POS
	STA TRANSITION_BACKGROUND_Y + 2
	STZ TRANSITION_BACKGROUND_X
	STZ TRANSITION_BACKGROUND_Y
	RTL
