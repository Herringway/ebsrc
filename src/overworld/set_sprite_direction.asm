
SET_SPRITE_DIRECTION:
	BEGIN_C_FUNCTION_FAR
	STACK_RESERVE_VARS
	STACK_RESERVE_INT16
	STACK_RESERVE_PARAM_INT16
	STACK_RESERVE_PARAM_INT16
	END_STACK_VARS
	STX @VIRTUAL02
	TAX
	JSL FIND_ENTITY_BY_SPRITE
	STA @LOCAL00
	CMP #.LOWORD(-1)
	BEQ @UNKNOWN0
	ASL
	CLC
	ADC #.LOWORD(ENTITY_DIRECTIONS)
	TAX
	LDA __BSS_START__,X
	CMP @VIRTUAL02
	BEQ @UNKNOWN0
	LDA @VIRTUAL02
	STA __BSS_START__,X
	LDA @LOCAL00
	JSL UPDATE_ENTITY_SPRITE
@UNKNOWN0:
	END_C_FUNCTION
