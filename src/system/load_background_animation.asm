	STA @VIRTUAL04
	JSL PREPARE_FOR_IMMEDIATE_DMA
	LDA #$0009
	JSL SET_BG_MODE
	LDY #$0000
	LDX #$5800
	TYA ;BG_TILEMAP_SIZE::NORMAL
	JSL SET_BG1_VRAM_LOCATION
	LDY #$1000
	LDX #$5C00
	LDA #BG_TILEMAP_SIZE::NORMAL
	JSL SET_BG2_VRAM_LOCATION
	LDY #$0004
	LDX @VIRTUAL02
	LDA @VIRTUAL04
	JSL LOAD_BATTLE_BG
	JSL SET_FORCE_BLANK
	PLD
	RTL
