
INTERACT_ESCALATOR:
	BEGIN_C_FUNCTION
	STACK_RESERVE_VARS
	STACK_RESERVE_INT32
	STACK_RESERVE_INT16
	STACK_RESERVE_INT16
	STACK_RESERVE_INT16
	STACK_RESERVE_INT16
	STACK_RESERVE_INT16
	STACK_RESERVE_INT16
	STACK_RESERVE_PARAM_INT16
	STACK_RESERVE_PARAM_INT16
	STACK_RESERVE_PARAM_INT16
	END_STACK_VARS
	STY @LOCAL06
	STX @LOCAL05
	STA @LOCAL04
	LDA DEMO_FRAMES_LEFT
	BNEL @UNKNOWN4
	JSL CLEAR_AUTO_MOVEMENT_DEMO
	LDX @LOCAL05
	TXA
	ASL
	ASL
	ASL
	TAX
	STX @LOCAL03
	LDY @LOCAL06
	TYA
	ASL
	ASL
	ASL
	STA @LOCAL02
	LDA @LOCAL04
	AND #$8000
	BEQ @UNKNOWN2
	LDY #.LOWORD(GAME_STATE) + game_state::walking_style
	LDA __BSS_START__,Y
	CMP #12
	BNEL @UNKNOWN4
	LDA #0
	STA __BSS_START__,Y
	LDA #3
	STA PLAYER_MOVEMENT_FLAGS
	LDA ESCALATOR_ENTRANCE_DIRECTION
	XBA
	AND #$00FF
	ASL
	STA @VIRTUAL02
	TXA
	LDX @VIRTUAL02
	CLC
	ADC f:ESCALATOR_EXIT_OFFSETS_X,X
	STA @VIRTUAL04
	LDA @LOCAL02
	STA @LOCAL00
	LDY @VIRTUAL04
	LDX GAME_STATE+game_state::leader_y_coord
	LDA GAME_STATE+game_state::leader_x_coord
	JSL RECORD_AUTO_MOVEMENT_DEMO
	TAY
	STY @LOCAL01
	LDX #16
	STX @LOCAL05
	LDX @VIRTUAL02
	LDA f:STAIR_INPUT_DIRECTION_MAP,X
	LDX @LOCAL05
	JSL RECORD_AUTO_MOVEMENT_DEMO_N_FRAMES_DIRECTION
	LOADPTR EXIT_ESCALATOR, @LOCAL00
	LDY @LOCAL01
	TYA
	INC
	JSL SCHEDULE_OVERWORLD_TASK
	JSL FINISH_AUTO_MOVEMENT_DEMO_AND_START
	STZ ESCALATOR_ENTRANCE_DIRECTION
	LDA #1
	STA MOVEMENT_NOT_NORMAL
	BRA @UNKNOWN3
@UNKNOWN2:
	LDA GAME_STATE+game_state::walking_style
	CMP #WALKING_STYLE::ESCALATOR
	BEQ @UNKNOWN4
	LDA #1
	STA MOVEMENT_NOT_NORMAL
	LDA @LOCAL04
	STA ESCALATOR_ENTRANCE_DIRECTION
	XBA
	AND #$00FF
	ASL
	STA @LOCAL06
	TAX
	LDA f:STAIR_INPUT_DIRECTION_MAP,X
	STA GAME_STATE+game_state::leader_direction
	LDA #3
	STA PLAYER_MOVEMENT_FLAGS
	LDA @LOCAL06
	PHA
	LDX @LOCAL03
	TXA
	PLX
	CLC
	ADC f:ESCALATOR_ENTRY_OFFSETS_X,X
	STA @VIRTUAL04
	LDA @LOCAL02
	STA @LOCAL00
	LDY @VIRTUAL04
	LDX GAME_STATE+game_state::leader_y_coord
	LDA GAME_STATE+game_state::leader_x_coord
	JSL RECORD_AUTO_MOVEMENT_DEMO
	TAX
	LOADPTR ENTER_ESCALATOR, @LOCAL00
	TXA
	INC
	JSL SCHEDULE_OVERWORLD_TASK
	JSL FINISH_AUTO_MOVEMENT_DEMO_AND_START
@UNKNOWN3:
	LDA @VIRTUAL04
	STA ESCALATOR_NEW_X
	LDA @LOCAL02
	STA ESCALATOR_NEW_Y
	LDA #.LOWORD(-1)
	STA STAIRS_DIRECTION
@UNKNOWN4:
	END_C_FUNCTION
